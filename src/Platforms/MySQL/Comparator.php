<?php

namespace Doctrine\DBAL\Platforms\MySQL;

use Doctrine\DBAL\Connection;
use Doctrine\DBAL\Exception;
use Doctrine\DBAL\Platforms\AbstractMySQLPlatform;
use Doctrine\DBAL\Schema\Comparator as BaseComparator;
use Doctrine\DBAL\Schema\Table;
use Doctrine\DBAL\Schema\TableDiff;

use function array_diff_assoc;
use function array_intersect_key;
use function count;
use function is_string;

/**
 * Compares schemas in the context of MySQL platform.
 *
 * In MySQL, unless specified explicitly, the column's character set and collation are inherited from its containing
 * table. So during comparison, an omitted value and the value that matches the default value of table in the
 * desired schema must be considered equal.
 */
class Comparator extends BaseComparator
{
    /** @var CollationMetadataProvider */
    private $collationMetadataProvider;

    /** @var Connection|null */
    private $connection;

    /**
     * The character set and collation that the implicit table options generated by the platform resolve to.
     *
     * @var array{charset: string, collation: string}|false|null
     */
    private $implicitTableOptions;

    /** @internal The comparator can be only instantiated by a schema manager. */
    public function __construct(
        AbstractMySQLPlatform $platform,
        CollationMetadataProvider $collationMetadataProvider,
        ?Connection $connection = null
    ) {
        parent::__construct($platform);

        $this->collationMetadataProvider = $collationMetadataProvider;
        $this->connection                = $connection;
    }

    /** @throws Exception */
    public function compareTables(Table $fromTable, Table $toTable): TableDiff
    {
        return parent::compareTables(
            $this->normalizeColumns($fromTable, $toTable),
            $this->normalizeColumns($toTable, $fromTable),
        );
    }

    /**
     * {@inheritDoc}
     */
    public function diffTable(Table $fromTable, Table $toTable)
    {
        return parent::diffTable(
            $this->normalizeColumns($fromTable, $toTable),
            $this->normalizeColumns($toTable, $fromTable),
        );
    }

    /** @throws Exception */
    private function normalizeColumns(Table $table, Table $otherTable): Table
    {
        $tableOptions = $this->getTableOptions($table, $otherTable);

        $usesImplicitTableOptions = count($tableOptions) > 0
            && ! $table->hasOption('charset')
            && ! $table->hasOption('collation');

        $table = clone $table;

        foreach ($table->getColumns() as $column) {
            $originalOptions   = $column->getPlatformOptions();
            $normalizedOptions = $this->normalizeOptions($originalOptions);

            $columnTableOptions = $tableOptions;

            // A column that specifies only the charset gets the default collation of the charset,
            // which may be different from the implicit table collation
            if (
                $usesImplicitTableOptions
                && isset($originalOptions['charset'])
                && ! isset($originalOptions['collation'])
            ) {
                unset($columnTableOptions['charset']);
            }

            $overrideOptions = array_diff_assoc($normalizedOptions, $columnTableOptions);

            if ($overrideOptions === $originalOptions) {
                continue;
            }

            $column->setPlatformOptions($overrideOptions);
        }

        return $table;
    }

    /**
     * Returns the character set and collation of the given table that its columns inherit by default.
     *
     * If the table doesn't specify them, it will be created with the implicit options generated by the platform
     * (DEFAULT CHARACTER SET utf8 COLLATE utf8_unicode_ci). The meaning of "utf8" depends on the server configuration
     * (e.g. it's utf8mb4 on MariaDB 13.1 and later unless the old_mode contains UTF8_IS_UTF8MB3), so the implicit
     * options are considered only if the other table has the options that they resolve to on the server.
     *
     * @return array<string,string>
     *
     * @throws Exception
     */
    private function getTableOptions(Table $table, Table $otherTable): array
    {
        $tableOptions = array_intersect_key($table->getOptions(), [
            'charset'   => null,
            'collation' => null,
        ]);

        if (
            count($tableOptions) > 0
            || $table->hasOption('collate')
            || $table->hasOption('table_options')
            || ! $otherTable->hasOption('charset')
            || ! $otherTable->hasOption('collation')
        ) {
            return $tableOptions;
        }

        $implicitTableOptions = $this->getImplicitTableOptions();

        if (
            $implicitTableOptions === null
            || $otherTable->getOption('charset') !== $implicitTableOptions['charset']
            || $otherTable->getOption('collation') !== $implicitTableOptions['collation']
        ) {
            return $tableOptions;
        }

        return $implicitTableOptions;
    }

    /**
     * @return array{charset: string, collation: string}|null
     *
     * @throws Exception
     */
    private function getImplicitTableOptions(): ?array
    {
        if ($this->implicitTableOptions === null) {
            $this->implicitTableOptions = false;

            if ($this->connection !== null) {
                $row = $this->connection->fetchNumeric(
                    <<<'SQL'
SELECT CHARSET(CONVERT('' USING utf8)),
       COLLATION(CONVERT('' USING utf8) COLLATE utf8_unicode_ci)
SQL
                    ,
                );

                if ($row !== false && is_string($row[0]) && is_string($row[1])) {
                    $this->implicitTableOptions = [
                        'charset'   => $row[0],
                        'collation' => $row[1],
                    ];
                }
            }
        }

        if ($this->implicitTableOptions === false) {
            return null;
        }

        return $this->implicitTableOptions;
    }

    /**
     * @param array<string,string> $options
     *
     * @return array<string,string>
     */
    private function normalizeOptions(array $options): array
    {
        if (isset($options['collation']) && ! isset($options['charset'])) {
            $charset = $this->collationMetadataProvider->getCollationCharset($options['collation']);

            if ($charset !== null) {
                $options['charset'] = $charset;
            }
        }

        return $options;
    }
}
